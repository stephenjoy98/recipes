package com.stephenjoy.recipes.backup

import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.tasks.await

data class Account(val uid: String, val name: String, val email: String, val photoUrl: String?)

/** Google sign-in through Credential Manager, exchanged for a Firebase Auth session. */
class AuthManager(private val appContext: Context) {

    private val _account = MutableStateFlow<Account?>(null)
    val account: StateFlow<Account?> = _account.asStateFlow()

    /** False when the app was built without google-services.json. */
    val isConfigured: Boolean get() = FirebaseApp.getApps(appContext).isNotEmpty() && webClientId() != null

    private val auth: FirebaseAuth? get() = if (FirebaseApp.getApps(appContext).isNotEmpty()) FirebaseAuth.getInstance() else null

    init {
        auth?.addAuthStateListener { fa ->
            _account.value = fa.currentUser?.let {
                Account(it.uid, it.displayName.orEmpty(), it.email.orEmpty(), it.photoUrl?.toString())
            }
        }
    }

    val currentUid: String? get() = auth?.currentUser?.uid

    /** [activityContext] must be an Activity so the account picker can be shown. */
    suspend fun signIn(activityContext: Context) {
        val clientId = webClientId()
        val firebaseAuth = auth
        check(clientId != null && firebaseAuth != null) {
            "Google sign-in isn't set up. Add your Firebase google-services.json and rebuild."
        }
        val option = GetSignInWithGoogleOption.Builder(clientId).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
        check(credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Unexpected credential type"
        }
        val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        firebaseAuth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await()
    }

    suspend fun signOut() {
        auth?.signOut()
        runCatching { CredentialManager.create(appContext).clearCredentialState(ClearCredentialStateRequest()) }
    }

    /** OAuth web client id generated by the google-services plugin, looked up by name so the
     *  app still compiles when Firebase isn't configured. */
    private fun webClientId(): String? {
        val res = appContext.resources.getIdentifier("default_web_client_id", "string", appContext.packageName)
        return if (res != 0) appContext.getString(res) else null
    }
}
